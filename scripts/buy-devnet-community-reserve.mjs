import assert from 'node:assert/strict';
import bs58 from 'bs58';
import { getAssociatedTokenAddressSync, TOKEN_2022_PROGRAM_ID, TOKEN_PROGRAM_ID } from '@solana/spl-token';
import { Connection, Keypair, PublicKey, Transaction, clusterApiUrl } from '@solana/web3.js';
import { buildTradeTransaction } from '../pump-trading.js';

const mintArg = process.argv.find(arg => arg.startsWith('--mint='))?.slice(7);
assert(mintArg, 'Pass --mint=<verified Devnet launch>.');
assert.equal(process.env.VITE_SOLANA_CLUSTER, 'devnet');
const mint = new PublicKey(mintArg);
const issuer = Keypair.fromSecretKey(bs58.decode(process.env.SOLANA_DEVNET_CREATOR_SECRET_KEY || ''));
const feeOwner = new PublicKey(process.env.VITE_FUNDED_TRADE_FEE_OWNER);
const connection = new Connection(process.env.SOLANA_DEVNET_RPC_URL || process.env.SOLANA_RPC_URL || clusterApiUrl('devnet'), 'finalized');
assert.equal(await connection.getGenesisHash(), await new Connection(clusterApiUrl('devnet')).getGenesisHash(), 'Configured RPC is not Devnet.');
const launches = await (await fetch('http://127.0.0.1:8788/api/launches')).json();
const launch = launches.find(row => row.mint === mint.toBase58());
assert(launch?.onchainVerified && launch.creatorWallet === issuer.publicKey.toBase58(), 'Issuer did not create this verified launch.');
const reserved = Number(launch.communityAirdrop?.reservedTokens);
assert(Number.isSafeInteger(reserved) && reserved > 0, 'No published reserve for this launch.');
const mintInfo = await connection.getParsedAccountInfo(mint, 'finalized');
const tokenProgram = mintInfo.value?.owner;
assert(tokenProgram?.equals(TOKEN_PROGRAM_ID) || tokenProgram?.equals(TOKEN_2022_PROGRAM_ID), 'Unsupported token program.');
const decimals = Number(mintInfo.value?.data?.parsed?.info?.decimals);
const required = BigInt(reserved) * 10n ** BigInt(decimals);
const source = getAssociatedTokenAddressSync(mint, issuer.publicKey, false, tokenProgram);
const balance = async () => BigInt((await connection.getTokenAccountBalance(source, 'finalized').catch(() => ({ value:{ amount:'0' } }))).value.amount);
const before = await balance();
assert(before < required, 'Issuer already has the full reserve; another buy is unnecessary.');
const amountSol = 0.035;
const quote = await buildTradeTransaction({ connection, side:'buy', mint, user:issuer.publicKey, amount:amountSol, slippagePercent:3, feeOwner });
assert(BigInt(quote.outputAmount.toString()) >= required - before, 'Bounded buy quote cannot fund the reserve.');
console.log(JSON.stringify({ execute:process.argv.includes('--execute'), mint:mint.toBase58(), issuer:issuer.publicKey.toBase58(), requiredBaseUnits:required.toString(), issuerBeforeBaseUnits:before.toString(), maxBuySol:amountSol, quotedBaseUnits:quote.outputAmount.toString(), appFeeLamports:quote.feeLamports }));
if (!process.argv.includes('--execute')) process.exit(0);
const latest = await connection.getLatestBlockhash('finalized');
const tx = new Transaction({ feePayer:issuer.publicKey, recentBlockhash:latest.blockhash }).add(...quote.instructions);
tx.sign(issuer);
const signature = await connection.sendRawTransaction(tx.serialize(), { skipPreflight:false });
const confirmation = await connection.confirmTransaction({ signature, blockhash:latest.blockhash, lastValidBlockHeight:latest.lastValidBlockHeight }, 'finalized');
assert.equal(confirmation.value.err, null, `Devnet buy failed: ${signature}`);
const after = await balance();
assert(after >= required, 'Finalized issuer token balance remains below the published reserve.');
const receipt = await connection.getTransaction(signature, { commitment:'finalized', maxSupportedTransactionVersion:0 });
const ownerIndex = receipt.transaction.message.accountKeys.findIndex(key => key.equals(feeOwner));
assert(ownerIndex >= 0, 'App-owner trading fee recipient is missing from the transaction.');
const ownerDelta = receipt.meta.postBalances[ownerIndex] - receipt.meta.preBalances[ownerIndex];
assert.equal(ownerDelta, quote.feeLamports, 'App-owner trading fee delta differs from the quote.');
console.log(JSON.stringify({ status:'reserve-tokens-purchased', mint:mint.toBase58(), signature, issuerAfterBaseUnits:after.toString(), tokenDeltaBaseUnits:(after-before).toString(), ownerFeeDeltaLamports:ownerDelta, finalized:true }));
