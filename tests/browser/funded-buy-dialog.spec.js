import {test,expect} from '@playwright/test';
import {PROTOCOL_FEE_SPLIT} from '../../config/protocol-fee-split.js';
for(const width of [320, 1440])test(`Buy more opens shared popup and preserves creation at ${width}px (mocked APIs)`,async({page},info)=>{
 await page.setViewportSize({width,height:900});
 await page.addInitScript(()=>sessionStorage.setItem('funded.app.wallet.manual-disconnect','1'));
 await page.route('https://**/*',r=>r.abort());await page.route('**/api/**',r=>r.fulfill({status:503,json:{error:'Offline fixture'}}));
 await page.route('**/api/fee-policy',r=>r.fulfill({json:{split:PROTOCOL_FEE_SPLIT}}));
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/#launch');await expect(page.locator('body')).toHaveClass(/product-flows-ready/);
 await page.locator('#token-name').fill('My community');await page.locator('#token-symbol').fill('COM');await page.locator('#launch-next').click();
 await expect(page.locator('#launch-promotion-options > summary')).toHaveCount(0);
 await page.locator('.creator-burn-card[data-burn-tier="pro"]').click();
 const trigger=page.locator('.launch-tier-buy-link');await trigger.click();
 const dialog=page.getByRole('dialog',{name:'Buy $FUNDED',exact:true});await expect(dialog).toBeVisible();
 await expect(page).toHaveURL(/#launch$/);await expect(dialog.locator('#funded-buy-amount')).toBeVisible();
 await expect(page.locator('#funded-buy-amount')).toHaveCount(1);await expect(dialog.locator('#funded-buy-submit')).toBeDisabled();
 expect(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true);
 await page.screenshot({path:info.outputPath(`buy-dialog-${width}.png`)});
 await page.keyboard.press('Escape');await expect(dialog).not.toBeVisible();await expect(trigger).toBeFocused();
 await expect(page.locator('#buybacks #funded-buy-amount')).toHaveCount(1);
 await trigger.click();await dialog.getByRole('button',{name:'Close buy dialog'}).click();
 await expect(page.locator('#launch-dialog')).toHaveAttribute('data-step','2');
 await page.locator('#launch-back').click();await expect(page.locator('#token-name')).toHaveValue('My community');
 expect(errors).toEqual([]);
});
